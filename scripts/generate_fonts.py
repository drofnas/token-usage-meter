#!/usr/bin/env python3
"""Generate the firmware's 2-bit DejaVu glyphs; requires Pillow and DejaVu Sans 2.37."""
import argparse
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = (('small', 9, False), ('label', 11, True), ('body', 12, False),
         ('title', 16, True), ('provider', 23, True), ('quota', 34, True))


def generate(directory):
    lines = ['// Generated by scripts/generate_fonts.py. DejaVu license: assets/fonts/LICENSE.',
             '#pragma once', '#include <cstdint>', 'namespace meter::font {',
             'struct Glyph { uint32_t offset; uint8_t width,height,advance; int8_t left,top; };',
             'struct Font { const uint8_t *data; const Glyph *glyphs; uint8_t height; };']
    for name, size, bold in FONTS:
        source = directory / ('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')
        font = ImageFont.truetype(str(source), size)
        top = font.getbbox('H')[1]
        pixels, glyphs = [], []
        for code in range(32, 128):
            char = chr(code) if code < 127 else '°'
            left, y, right, bottom = font.getbbox(char)
            width, height = right-left, bottom-y
            image = Image.new('L', (max(1, width), max(1, height)))
            ImageDraw.Draw(image).text((-left, -y), char, font=font, fill=255)
            levels = [min(3, (value+42)//85) for value in image.getdata()] if width*height else []
            offset = len(pixels)
            for index in range(0, len(levels), 4):
                group = levels[index:index+4] + [0]*3
                pixels.append(sum(group[i] << (i*2) for i in range(4)))
            advance = math.ceil(font.getlength(char))
            assert 0 <= width < 256 and 0 <= height < 256 and 0 <= advance < 256
            glyphs.append((offset, width, height, advance, left, y-top))
        lines.append(f'inline constexpr uint8_t {name}_data[]={{')
        lines.extend(','.join(str(n) for n in pixels[i:i+32])+',' for i in range(0,len(pixels),32))
        lines.append('};')
        lines.append(f'inline constexpr Glyph {name}_glyphs[]={{')
        lines.extend('{'+','.join(map(str,g))+'},' for g in glyphs)
        lines.extend(['};', f'inline constexpr Font {name}{{{name}_data,{name}_glyphs,{size}}};'])
    lines.append('} // namespace meter::font')
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('font_directory', type=Path)
    args = parser.parse_args()
    output = ROOT / 'firmware/components/meter_network/fonts.h'
    output.write_text(generate(args.font_directory))
    print(f'Generated {output.name}: {output.stat().st_size} source bytes')
